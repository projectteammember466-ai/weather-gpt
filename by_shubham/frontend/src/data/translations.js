export function localizeCondition(condition = '', lang = 'en') {
  if (!condition) return '';
  if (lang === 'en') return condition;
  const clean = condition.trim().toLowerCase();
  const match = WEATHER_CONDITIONS_MAP[clean];
  if (match && match[lang]) return match[lang];
  return condition;
}

export function getTranslation(lang = 'en', key = '', fallback = '') {
  if (!key) return fallback || '';
  const currentLang = TRANSLATIONS[lang] || TRANSLATIONS.en;
  
  // 1. Direct key match
  if (currentLang[key] !== undefined) return currentLang[key];
  if (TRANSLATIONS.en[key] !== undefined) return TRANSLATIONS.en[key];

  // 2. Dot notation resolution (e.g. "context.general.name" or "weather.temperature")
  if (key.includes('.')) {
    const parts = key.split('.');
    let cur = currentLang;
    for (const part of parts) {
      if (cur && typeof cur === 'object' && part in cur) {
        cur = cur[part];
      } else {
        cur = undefined;
        break;
      }
    }
    if (cur !== undefined && typeof cur === 'string') return cur;

    let fallbackCur = TRANSLATIONS.en;
    for (const part of parts) {
      if (fallbackCur && typeof fallbackCur === 'object' && part in fallbackCur) {
        fallbackCur = fallbackCur[part];
      } else {
        fallbackCur = undefined;
        break;
      }
    }
    if (fallbackCur !== undefined && typeof fallbackCur === 'string') return fallbackCur;
  }

  // 3. Fallback or key itself
  return fallback || key;
}
